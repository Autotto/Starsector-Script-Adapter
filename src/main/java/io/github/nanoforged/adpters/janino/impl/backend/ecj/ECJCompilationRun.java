package io.github.nanoforged.adpters.janino.impl.backend.ecj;

import io.github.nanoforged.adpters.janino.api.comp.CompilationException;
import io.github.nanoforged.adpters.janino.api.comp.CompilationOutput;
import io.github.nanoforged.adpters.janino.api.comp.TypeResolver;

import org.eclipse.jdt.core.compiler.CategorizedProblem;
import org.eclipse.jdt.internal.compiler.ClassFile;
import org.eclipse.jdt.internal.compiler.CompilationResult;
import org.eclipse.jdt.internal.compiler.Compiler;
import org.eclipse.jdt.internal.compiler.DefaultErrorHandlingPolicies;
import org.eclipse.jdt.internal.compiler.ICompilerRequestor;
import org.eclipse.jdt.internal.compiler.IErrorHandlingPolicy;
import org.eclipse.jdt.internal.compiler.IProblemFactory;
import org.eclipse.jdt.internal.compiler.classfmt.ClassFileConstants;
import org.eclipse.jdt.internal.compiler.env.ICompilationUnit;
import org.eclipse.jdt.internal.compiler.impl.CompilerOptions;

import java.io.PrintWriter;
import java.io.Writer;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * One isolated compilation request: it owns the ECJ compiler options, the name environment, the
 * generated class files and the discovered source units for a single
 * {@link ECJCompilerBackEnd#compile} call.
 *
 * <p><strong>Compilation units.</strong> The initial unit is the request source. Types referenced by
 * it are resolved by {@link ECJNameEnvironment}: binaries are fed back as class files, and source
 * files are answered as additional compilation units. ECJ compiles those discovered units in the
 * same pass while their bindings are being built; units that are only discovered once the current
 * compiler pass is winding down are collected and handed to a new compiler in a following round.
 * Every round shares this run's state, so the last round links against the classes generated by the
 * earlier ones. The loop ends when no discovered unit is left uncompiled.
 *
 * <p><strong>Diagnostics.</strong> Compiler errors are formatted as
 * {@code file:line:column: message} and reported through a single
 * {@link CompilationException}. Warnings are dropped because the Janino adapter API has no warning
 * channel and because a translation layer must not reject classes for warnings that the original
 * Janino pipeline accepted.
 *
 * <p>The run is confined to the thread that created it and is discarded after one request.
 */
final class ECJCompilationRun {

    /** Upper bound of compiler rounds, a defence against resolvers that keep answering new units. */
    private static final int MAX_COMPILE_ROUNDS = 64;

    /** Root description used in diagnostics. */
    private final String className;

    /** Class files generated so far, keyed by dotted binary name (including member type names). */
    private final Map<String, byte[]> generatedClasses = new LinkedHashMap<>();

    /** Source units discovered so far, keyed by slash separated source file name. */
    private final Map<String, ECJCompilationUnit> discoveredUnits = new LinkedHashMap<>();

    /** Source file names for which a compilation result has been delivered. */
    private final Set<String> compiledUnitFileNames = new LinkedHashSet<>();

    /** Explicit root compilation units; also the first round's input. */
    private final List<ECJCompilationUnit> initialUnits = new ArrayList<>();

    /** Actual source resource for each emitted binary class, including secondary top-level types. */
    private final Map<String, String> sourceResources = new LinkedHashMap<>();

    /** Name environment shared by all rounds of this request. */
    private final ECJNameEnvironment nameEnvironment;

    /** Error handling policy: collect every problem of a round instead of stopping at the first one. */
    private final IErrorHandlingPolicy errorHandlingPolicy = DefaultErrorHandlingPolicies.exitAfterAllProblems();

    /** Problems are created in English so that game logs stay stable across host locales. */
    private final IProblemFactory problemFactory = RootProblemFactory.INSTANCE;

    /**
     * Creates the state for one compilation request.
     *
     * @param roots        explicit top-level binary names to source text
     * @param typeResolver resolver that provides all other types
     */
    ECJCompilationRun(Map<String, String> roots, TypeResolver typeResolver) {
        this.className = roots.size() == 1 ? roots.keySet().iterator().next() : roots.keySet().toString();
        /* Package paths that are declared type names, shared with the name environment. */
        Set<String> declaredTypePackagePaths = new LinkedHashSet<>();
        this.nameEnvironment = new ECJNameEnvironment(
                typeResolver, this.generatedClasses, this.discoveredUnits, declaredTypePackagePaths);
        Map<String, String> rootBySourceFile = new LinkedHashMap<>();
        for (Map.Entry<String, String> root : roots.entrySet()) {
            ECJCompilationUnit unit = ECJCompilationUnit.forClassName(root.getKey(), root.getValue());
            String sourceFile = unit.fileNameAsString();
            String previousRoot = rootBySourceFile.putIfAbsent(sourceFile, root.getKey());
            if (previousRoot != null) {
                throw new IllegalArgumentException("roots '" + previousRoot + "' and '" + root.getKey()
                        + "' share the source resource '" + sourceFile + "'");
            }
            this.initialUnits.add(this.nameEnvironment.register(unit));
        }
    }

    /**
     * Compiles the request source and its transitive source closure.
     *
     * @return generated class files and their actual source resource provenance
     * @throws CompilationException if the source has errors or the compiler fails internally
     */
    CompilationOutput run() {
        compileUnits();
        return new CompilationOutput(this.generatedClasses, this.sourceResources);
    }

    /**
     * Transfers generated bytes to a single-entry caller without public snapshot copy overhead.
     *
     * @return caller-owned map and bytes, never retained outside this discarded run
     */
    Map<String, byte[]> runClassFiles() {
        compileUnits();
        return new LinkedHashMap<>(this.generatedClasses);
    }

    /** Compiles all roots and discovered sources before exposing any successful output. */
    private void compileUnits() {
        List<ECJCompilationUnit> pending = this.initialUnits;
        for (int round = 1; !pending.isEmpty(); round++) {
            if (round > MAX_COMPILE_ROUNDS) {
                throw new CompilationException(
                        "ECJ did not finish the source closure of '" + this.className + "' after "
                                + MAX_COMPILE_ROUNDS + " rounds",
                        new IllegalStateException("uncompiled source units: " + fileNames(pending)));
            }
            int compiledBefore = this.compiledUnitFileNames.size();
            int discoveredBefore = this.discoveredUnits.size();
            RoundRequestor requestor = new RoundRequestor();
            compileRound(pending, requestor);
            if (!requestor.errors.isEmpty()) {
                throw new CompilationException(requestor.errors);
            }
            pending = pendingUnits();
            if (!pending.isEmpty()
                    && this.compiledUnitFileNames.size() == compiledBefore
                    && this.discoveredUnits.size() == discoveredBefore) {
                throw new CompilationException(
                        "ECJ made no progress while compiling the source closure of '" + this.className + "'",
                        new IllegalStateException("uncompiled source units: " + fileNames(pending)));
            }
        }
    }

    /**
     * Runs one ECJ compiler pass over the given units.
     *
     * @param units     units that must be compiled in this pass
     * @param requestor requestor of this pass
     * @throws CompilationException if the compiler fails for a non-diagnostic reason
     */
    private void compileRound(List<ECJCompilationUnit> units, ICompilerRequestor requestor) {
        Compiler compiler = new Compiler(
                this.nameEnvironment,
                this.errorHandlingPolicy,
                compilerOptions(),
                requestor,
                this.problemFactory,
                new PrintWriter(Writer.nullWriter(), true),
                null);
        // The name environment is a per-run object; concurrent compiler workers would race on it.
        compiler.useSingleThread = true;
        try {
            compiler.compile(units.toArray(new ICompilationUnit[0]));
        } catch (CompilationException e) {
            throw e;
        } catch (RuntimeException e) {
            throw new CompilationException("ECJ failed to compile '" + this.className + "'", e);
        }
    }

    /**
     * Creates the compiler options of the adapter: Java 17 language level, Java 17 class files and
     * full debug attributes (source file name, line numbers and local variable names).
     *
     * <p>The levels are set through {@link CompilerOptions#set(Map)} as a batch compiler would, and
     * then pinned to {@link ClassFileConstants#JDK17} so that a future ECJ default cannot silently
     * change the language level. No {@code --release} option is used: ECJ must not try to discover
     * the platform classes of the running JDK, the {@link TypeResolver} is the only class source.
     *
     * @return options for one round
     */
    private static CompilerOptions compilerOptions() {
        Map<String, String> settings = Map.of(
                CompilerOptions.OPTION_Compliance, CompilerOptions.VERSION_17,
                CompilerOptions.OPTION_Source, CompilerOptions.VERSION_17,
                CompilerOptions.OPTION_TargetPlatform, CompilerOptions.VERSION_17,
                // Warnings are not exposed by this adapter; avoid warning-only resource flow work.
                CompilerOptions.OPTION_ReportUnclosedCloseable, CompilerOptions.IGNORE,
                CompilerOptions.OPTION_ReportPotentiallyUnclosedCloseable, CompilerOptions.IGNORE,
                CompilerOptions.OPTION_ReportExplicitlyClosedAutoCloseable, CompilerOptions.IGNORE);
        CompilerOptions options = new CompilerOptions(settings);
        options.complianceLevel = ClassFileConstants.JDK17;
        options.sourceLevel = ClassFileConstants.JDK17;
        options.targetJDK = ClassFileConstants.JDK17;
        options.produceDebugAttributes =
                ClassFileConstants.ATTR_SOURCE | ClassFileConstants.ATTR_LINES | ClassFileConstants.ATTR_VARS;
        options.verbose = false;
        return options;
    }

    /**
     * Answers the discovered units that have not produced a compilation result yet.
     *
     * @return units for the next round, in discovery order
     */
    private List<ECJCompilationUnit> pendingUnits() {
        List<ECJCompilationUnit> pending = new ArrayList<>();
        for (Map.Entry<String, ECJCompilationUnit> entry : this.discoveredUnits.entrySet()) {
            if (!this.compiledUnitFileNames.contains(entry.getKey())) pending.add(entry.getValue());
        }
        return pending;
    }

    /**
     * Formats problems of one compilation result and stores generated class files.
     */
    private final class RoundRequestor implements ICompilerRequestor {

        /** Formatted compiler errors of this round. */
        private final List<String> errors = new ArrayList<>();

        /**
         * {@inheritDoc}
         *
         * <p>All problems are inspected; warnings are ignored, errors are formatted. Class files are
         * only recorded for results without errors, because ECJ does not produce a usable class file
         * for a unit that failed.
         */
        @Override
        public void acceptResult(CompilationResult result) {
            if (result == null) return;

            String unitFileName = unitFileName(result);
            if (unitFileName != null) ECJCompilationRun.this.compiledUnitFileNames.add(unitFileName);

            // ECJ answers null (not an empty array) when a unit compiled without any problem.
            CategorizedProblem[] problems = result.getProblems();
            if (problems != null) {
                for (CategorizedProblem problem : problems) {
                    if (problem.isError()) this.errors.add(formatProblem(problem, unitFileName));
                }
            }
            if (result.hasErrors()) return;

            for (ClassFile classFile : result.getClassFiles()) {
                String name = binaryName(classFile.getCompoundName());
                ECJCompilationRun.this.generatedClasses.put(name, classFile.getBytes());
                if (unitFileName != null) ECJCompilationRun.this.sourceResources.put(name, unitFileName);
            }
        }
    }

    /**
     * Answers the source file name of a compilation result.
     *
     * @param result compilation result handed to the requestor
     * @return slash separated source file name, or {@code null} if the result has none
     */
    private static String unitFileName(CompilationResult result) {
        ICompilationUnit unit = result.getCompilationUnit();
        char[] name = unit != null ? unit.getFileName() : result.getFileName();
        return name == null ? null : new String(name);
    }

    /**
     * Formats one problem as {@code file:line:column: message}.
     *
     * @param problem      the ECJ problem
     * @param fallbackName file name of the result the problem was reported for
     * @return the single line diagnostic
     */
    private String formatProblem(CategorizedProblem problem, String fallbackName) {
        char[] originatingFileName = problem.getOriginatingFileName();
        String fileName = originatingFileName != null
                ? new String(originatingFileName)
                : fallbackName != null ? fallbackName : "<unknown>";
        int line = Math.max(problem.getSourceLineNumber(), 0);
        int column = columnNumber(problem, fileName);
        return fileName + ':' + line + ':' + column + ": " + problem.getMessage();
    }

    /**
     * Computes the 1-based column of a problem within its source line.
     *
     * <p>ECJ reports the absolute character offset and the line number. The column is derived by
     * scanning backwards to the preceding line separator in the cached source text; problems
     * without a source position answer column {@code 0}.
     *
     * @param problem  the ECJ problem
     * @param fileName originating source file name
     * @return 1-based column, or {@code 0} when it cannot be determined
     */
    private int columnNumber(CategorizedProblem problem, String fileName) {
        int sourceStart = problem.getSourceStart();
        if (sourceStart < 0) return 0;
        ECJCompilationUnit unit = this.discoveredUnits.get(fileName);
        if (unit == null) return 0;
        char[] contents = unit.getContents();
        if (sourceStart >= contents.length) return 0;
        int lineStart = 0;
        for (int i = sourceStart - 1; i >= 0; i--) {
            char character = contents[i];
            if (character == '\n' || character == '\r') {
                lineStart = i + 1;
                break;
            }
        }
        return sourceStart - lineStart + 1;
    }

    /**
     * Joins a class file compound name with dots.
     *
     * @param compoundName class file compound name, for example {@code {{a}, {b}, {Outer$Inner}}}
     * @return dotted binary name
     */
    private static String binaryName(char[][] compoundName) {
        StringBuilder name = new StringBuilder();
        for (int i = 0; i < compoundName.length; i++) {
            if (i > 0) name.append('.');
            name.append(compoundName[i]);
        }
        return name.toString();
    }

    /**
     * Extracts the file names of some source units for error messages.
     *
     * @param units source units
     * @return source file names of the given units
     */
    private static List<String> fileNames(List<ECJCompilationUnit> units) {
        List<String> names = new ArrayList<>(units.size());
        for (ECJCompilationUnit unit : units) names.add(unit.fileNameAsString());
        return names;
    }
}
